// Kit asset workflow — see engine/kit/ASSETS.md
//   node tools/kit-asset.mjs new <category>/<name>      scaffold a new asset (draft)
//   node tools/kit-asset.mjs check <category>/<name>    lint + render out/assets/<category>-<name>.png
//   node tools/kit-asset.mjs build                      catalogue engine/kit/assets.json + out/assets/gallery.html
//   node tools/kit-asset.mjs approve <category>/<name>  mark as approved (films only list approved assets)
//   node tools/kit-asset.mjs find <word> [--all]        search icons and assets
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'engine/kit/assets'), OUT = path.join(ROOT, 'out/assets');
const APPROVED = path.join(ROOT, 'engine/kit/assets-approved.json');
const [cmd, arg] = process.argv.slice(2);
const die = m => { console.error(`✖ ${m}`); process.exit(1); };
const approved = () => (fs.existsSync(APPROVED) ? JSON.parse(fs.readFileSync(APPROVED, 'utf8')) : []);
const fileOf = n => path.join(DIR, `${n}.js`);
const validName = n => /^[a-z0-9-]+\/[a-z0-9-]+$/.test(n ?? '');

function list() {
  const out = [];
  if (!fs.existsSync(DIR)) return out;
  for (const cat of fs.readdirSync(DIR)) if (fs.statSync(path.join(DIR, cat)).isDirectory()) for (const f of fs.readdirSync(path.join(DIR, cat))) if (f.endsWith('.js')) out.push(`${cat}/${f.slice(0, -3)}`);
  return out.sort();
}
const load = async n => (await import(pathToFileURL(fileOf(n)).href + `?v=${fs.statSync(fileOf(n)).mtimeMs}`)).default;

// static + metadata checks; returns a list of problems
async function lint(n) {
  const src = fs.readFileSync(fileOf(n), 'utf8'), bad = [];
  for (const [re, why] of [[/Math\.random/, 'Math.random (use k.hash)'], [/\bDate\b|performance\./, 'clock access'], [/set(Timeout|Interval)|requestAnimationFrame/, 'timers'],
    [/\bfetch\s*\(|XMLHttpRequest|WebSocket/, 'network access'], [/\bdocument\.|\bwindow\.|localStorage|globalThis/, 'DOM / globals'], [/^\s*import\b|\bimport\s*\(/m, 'imports'], [/\beval\b|new Function/, 'eval']])
    if (re.test(src)) bad.push(`forbidden: ${why}`);
  let a;
  try { a = await load(n); } catch (e) { return [...bad, `does not load: ${e.message}`]; }
  const [cat, name] = n.split('/');
  if (a.name !== name || a.category !== cat) bad.push(`name/category must be "${name}"/"${cat}"`);
  if (!a.desc) bad.push('desc missing');
  if (!Array.isArray(a.tags) || a.tags.length < 3) bad.push('give at least 3 tags (Turkish + English)');
  if (!Array.isArray(a.box) || a.box.length !== 4 || a.box[2] <= a.box[0] || a.box[3] <= a.box[1]) bad.push('box must be [x0, y0, x1, y1]');
  if (typeof a.draw !== 'function') bad.push('draw(ctx, t, p, k) missing');
  for (const [k, d] of Object.entries(a.params ?? {})) {
    if (!['color', 'time', 'number', 'enum', 'text'].includes(d.type)) bad.push(`param ${k}: unknown type ${d.type}`);
    if (!('default' in d)) bad.push(`param ${k}: default missing`);
    if (d.type === 'enum' && !d.values?.includes(d.default)) bad.push(`param ${k}: default not in values`);
  }
  for (const [k, [x, y]] of Object.entries(a.points ?? {}))
    if (a.box && (x < a.box[0] - 1 || x > a.box[2] + 1 || y < a.box[1] - 1 || y > a.box[3] + 1)) bad.push(`point ${k} lies outside box`);
  return bad;
}

// preview project: dark + light rows at several moments, variants, attach points; runtime checks run in the page
function writePreview(n, a) {
  const dir = path.join(ROOT, 'examples/_asset-check');
  fs.mkdirSync(dir, { recursive: true });
  const fire = Object.entries(a.params ?? {}).find(([, d]) => d.type === 'time')?.[0];
  const times = fire ? [0.3, 1.0, 1.02, 1.06, 1.25, 2.5] : [0, 0.5, 1, 1.5, 2.5, 4];
  const en = Object.entries(a.params ?? {}).find(([, d]) => d.type === 'enum');
  fs.writeFileSync(path.join(dir, 'project.json'), JSON.stringify({ name: '_asset-check', width: 1800, height: en ? 1200 : 820, fps: 30, duration: 1, subframes: 1,
    fonts: { css: ['@fontsource/jetbrains-mono/700.css'], preload: ["700 20px 'JetBrains Mono'"] } }, null, 2));
  fs.writeFileSync(path.join(dir, 'scene.js'), `// generated by tools/kit-asset.mjs check — do not edit
import A from '../../engine/kit/assets/${n}.js';
import { THEMES, assetKitFor } from '../../engine/kit/film.js';
const NAME = ${JSON.stringify(n)}, TIMES = ${JSON.stringify(times)}, FIRE = ${JSON.stringify(fire ?? null)}, ENUM = ${JSON.stringify(en ? [en[0], en[1].values] : null)};
const box = A.box, bw = box[2] - box[0], bh = box[3] - box[1];
const params = over => { const p = {}; for (const [k, d] of Object.entries(A.params ?? {})) p[k] = d.default; if (FIRE) p[FIRE] = 1; return { ...p, ...over }; };
function cell(ctx, pal, x, y, w, h, t, p, label, check) {
  ctx.fillStyle = \`rgb(\${pal.bg})\`; ctx.fillRect(x, y, w, h);
  const s = Math.min((w - 60) / bw, (h - 70) / bh), cx = x + w / 2 - (box[0] + bw / 2) * s, cy = y + 24 + (h - 40) / 2 - (box[1] + bh / 2) * s;
  ctx.save(); ctx.setLineDash([6, 6]); ctx.strokeStyle = 'rgba(128,128,140,0.5)'; ctx.lineWidth = 1.5; ctx.strokeRect(cx + box[0] * s, cy + box[1] * s, bw * s, bh * s); ctx.restore();
  ctx.save(); ctx.translate(cx, cy); ctx.scale(s, s); A.draw(ctx, t, p, assetKitFor(ctx, pal)); ctx.restore();
  for (const [k, [px, py]] of Object.entries(A.points ?? {})) {
    ctx.strokeStyle = 'rgb(64,212,255)'; ctx.lineWidth = 2; ctx.beginPath(); ctx.moveTo(cx + px * s - 8, cy + py * s); ctx.lineTo(cx + px * s + 8, cy + py * s); ctx.moveTo(cx + px * s, cy + py * s - 8); ctx.lineTo(cx + px * s, cy + py * s + 8); ctx.stroke();
    ctx.fillStyle = 'rgb(64,212,255)'; ctx.font = "700 13px 'JetBrains Mono'"; ctx.fillText(k, cx + px * s + 10, cy + py * s - 8);
  }
  ctx.fillStyle = pal.bg[0] > 128 ? 'rgba(0,0,0,0.6)' : 'rgba(255,255,255,0.6)'; ctx.font = "700 15px 'JetBrains Mono'"; ctx.fillText(label, x + 14, y + 24);
}
// runtime checks on an offscreen canvas: stays inside the box, same output for the same t
function audit() {
  const pad = 60 + (A.bleed ?? 0), c = new OffscreenCanvas(bw + 2 * pad, bh + 2 * pad), g = c.getContext('2d', { willReadFrequently: true }), pal = { ...THEMES.night, accent: THEMES.night.red };
  const render = (t, p) => { g.setTransform(1, 0, 0, 1, 0, 0); g.clearRect(0, 0, c.width, c.height); g.translate(pad - box[0], pad - box[1]); A.draw(g, t, p, assetKitFor(g, pal)); return g.getImageData(0, 0, c.width, c.height).data; };
  let outside = 0, maxOut = 0;
  for (const t of TIMES) {
    const d = render(t, params({}));
    for (let y = 0; y < c.height; y++) for (let x = 0; x < c.width; x++) {
      if (d[(y * c.width + x) * 4 + 3] < 40) continue;
      const b = A.bleed ?? 0, ox = Math.max(pad - b - x, x - (pad + bw + b), 0), oy = Math.max(pad - b - y, y - (pad + bh + b), 0);
      if (ox > 2 || oy > 2) { outside++; maxOut = Math.max(maxOut, ox, oy); }
    }
    const a = render(t, params({})), b = render(t, params({}));
    for (let i = 0; i < a.length; i += 97) if (a[i] !== b[i]) { console.error(\`asset: not deterministic at t=\${t}\`); break; }
  }
  if (outside > 40) console.error(\`asset: \${outside} px drawn outside box (up to \${maxOut} units)\`);
}
export default {
  setup() { audit(); },
  draw(ctx, t, { W, H }) {
    ctx.fillStyle = '#1a1a1f'; ctx.fillRect(0, 0, W, H);
    const cw = W / TIMES.length, ch = 400, themes = [['night', 0], ['paper', ch]];
    for (const [th, y] of themes) TIMES.forEach((tt, i) => cell(ctx, { ...THEMES[th], accent: THEMES[th].red }, i * cw + 2, y + 2, cw - 4, ch - 4, tt, params({}),
      \`\${th} · t=\${tt}\${FIRE && tt >= 1 ? \` (\${FIRE}+\${(tt - 1).toFixed(2)})\` : ''}\`));
    if (ENUM) ENUM[1].forEach((v, i) => cell(ctx, { ...THEMES.night, accent: THEMES.night.red }, i * cw + 2, 2 * ch + 2, cw - 4, ch - 4, 0.5, params({ [ENUM[0]]: v }), \`\${ENUM[0]}=\${v}\`));
    ctx.fillStyle = 'rgba(255,255,255,0.75)'; ctx.font = "700 18px 'JetBrains Mono'"; ctx.fillText(\`\${NAME} — \${A.desc}\`, 16, H - 14);
  },
};
`);
  return 'examples/_asset-check';
}

async function check(n) {
  if (!validName(n) || !fs.existsSync(fileOf(n))) die(`no asset ${n}`);
  const problems = await lint(n);
  if (problems.some(p => p.startsWith('does not load') || p.startsWith('forbidden'))) { problems.forEach(p => console.error(`  ✖ ${p}`)); process.exit(1); }
  const proj = writePreview(n, await load(n));
  const r = spawnSync('node', ['ft.mjs', 'stills', proj, '0s'], { cwd: ROOT, encoding: 'utf8', timeout: 180000 });
  const runtime = (r.stdout + r.stderr).split('\n').filter(l => /asset:|scene error|✖/.test(l) && !/404/.test(l)).map(l => l.replace(/^\[scene \w+\]\s*/, ''));
  fs.mkdirSync(OUT, { recursive: true });
  const png = path.join(OUT, `${n.replace('/', '-')}.png`);
  const still = path.join(ROOT, proj, 'out/stills/f00000.png');
  if (fs.existsSync(still)) fs.copyFileSync(still, png);
  const all = [...problems, ...runtime];
  all.forEach(p => console.log(`  ✖ ${p}`));
  console.log(`${all.length ? '✖' : '✓'} ${n} → ${path.relative(ROOT, png)}`);
  process.exitCode = all.length ? 1 : 0;
}

async function build() {
  const ok = new Set(approved()), cat = [];
  for (const n of list()) {
    try {
      const a = await load(n);
      cat.push({ name: n, status: ok.has(n) ? 'approved' : 'draft', desc: a.desc, tags: a.tags, anchor: a.anchor, box: a.box,
        points: Object.keys(a.points ?? {}), params: Object.fromEntries(Object.entries(a.params ?? {}).map(([k, d]) => [k, { type: d.type, default: d.default, ...(d.values ? { values: d.values } : {}), ...(d.desc ? { desc: d.desc } : {}) }])) });
    } catch (e) { console.error(`✖ ${n}: ${e.message}`); }
  }
  fs.writeFileSync(path.join(ROOT, 'engine/kit/assets.json'), JSON.stringify(cat, null, 1));
  fs.mkdirSync(OUT, { recursive: true });
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  fs.writeFileSync(path.join(OUT, 'gallery.html'), `<!doctype html><meta charset="utf-8"><title>Kit assets</title>
<style>body{background:#111;color:#ddd;font:14px system-ui;margin:24px}h1{font-size:20px}.a{margin:0 0 28px}.a img{width:100%;max-width:1400px;border-radius:8px;display:block}
.s{display:inline-block;padding:2px 8px;border-radius:9px;font-size:12px;margin-left:8px}.approved{background:#1e5c3a}.draft{background:#6b4b12}code{color:#9cf}</style>
<h1>Kit assets — ${cat.length} (${cat.filter(a => a.status === 'approved').length} approved)</h1>
${cat.map(a => `<div class="a"><b>${esc(a.name)}</b><span class="s ${a.status}">${a.status}</span> — ${esc(a.desc)}<br><small>tags: ${esc(a.tags.join(', '))} · points: ${esc(a.points.join(', ') || '—')} · params: <code>${esc(Object.keys(a.params).join(', ') || '—')}</code></small>
<img src="${a.name.replace('/', '-')}.png" alt="${esc(a.name)}"></div>`).join('\n')}`);
  console.log(`${cat.length} assets → engine/kit/assets.json, out/assets/gallery.html`);
}

if (cmd === 'new') {
  if (!validName(arg)) die('name must look like category/name (lowercase, dashes)');
  if (fs.existsSync(fileOf(arg))) die(`${arg} exists`);
  const [c, n] = arg.split('/');
  fs.mkdirSync(path.dirname(fileOf(arg)), { recursive: true });
  fs.writeFileSync(fileOf(arg), `// ${arg} — describe it in one line. Contract: engine/kit/ASSETS.md
export default {
  name: '${n}', category: '${c}',
  desc: '',
  tags: [],
  box: [-100, -100, 100, 100],
  anchor: 'centre',
  points: {},
  params: {
    color: { type: 'color', default: 'ink' },
  },
  draw(ctx, t, p, k) {
    ctx.fillStyle = k.rgba(p.color);
    ctx.beginPath(); k.rrect(-80, -80, 160, 160, 24); ctx.fill();
  },
};
`);
  console.log(`created ${path.relative(ROOT, fileOf(arg))}`);
} else if (cmd === 'check') await check(arg);
else if (cmd === 'build') await build();
else if (cmd === 'approve') {
  if (!fs.existsSync(fileOf(arg ?? '-'))) die(`no asset ${arg}`);
  const a = new Set(approved()); a.add(arg); fs.writeFileSync(APPROVED, JSON.stringify([...a].sort(), null, 1));
  await build();
} else if (cmd === 'find') {
  const q = (arg ?? '').toLowerCase(), all = process.argv.includes('--all');
  const cat = fs.existsSync(path.join(ROOT, 'engine/kit/assets.json')) ? JSON.parse(fs.readFileSync(path.join(ROOT, 'engine/kit/assets.json'), 'utf8')) : [];
  const hits = cat.filter(a => (all || a.status === 'approved') && (a.name.includes(q) || a.tags.some(t => t.toLowerCase().includes(q)) || a.desc.toLowerCase().includes(q)));
  console.log(`assets: ${hits.map(a => `${a.name}${a.status === 'draft' ? ' (draft)' : ''}`).join(', ') || '—'}`);
  spawnSync('node', ['tools/kit-icons-find.mjs', q], { cwd: ROOT, stdio: 'inherit' });
} else console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 7).map(l => l.replace(/^\/\/ ?/, '')).join('\n'));
